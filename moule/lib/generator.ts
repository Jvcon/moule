import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { spawnSync } from "node:child_process";
import type { ResolvedToolchain, MiseTool } from "./resolver";

const HEADER = "# Generated by moule — 用 `moule apply` 重新生成；手改可能被覆盖。";

export interface GeneratedFile {
  path: string;
  content: string;
}

export interface GeneratedSet {
  files: GeneratedFile[];
}

export type FileStatus = "create" | "change" | "unchanged";

function miseKey(t: MiseTool): string {
  if (!t.backend || t.backend === "core") return t.id;
  return t.plugin ? `${t.backend}:${t.plugin}` : `${t.backend}:${t.id}`;
}

export function renderMiseToml(tc: ResolvedToolchain): string {
  const lines: string[] = [HEADER, "", "[tools]"];
  const seen = new Set<string>();
  for (const t of tc.mise) {
    const key = miseKey(t);
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(`${JSON.stringify(key)} = ${JSON.stringify(t.version)}`);
  }
  return lines.join("\n") + "\n";
}

interface DevcontainerJson {
  [k: string]: unknown;
  customizations?: { vscode?: { extensions?: string[] } };
  features?: Record<string, unknown>;
  image?: string;
  build?: { dockerfile: string };
}

function fallbackDevcontainer(name: string): DevcontainerJson {
  return {
    name,
    image: "mcr.microsoft.com/devcontainers/base:ubuntu",
    features: { "ghcr.io/devcontainers-extra/features/mise:1": {} },
    customizations: { vscode: { extensions: ["hverlin.mise-vscode"] } },
    mounts: [],
    containerEnv: {},
    remoteEnv: {},
    postCreateCommand: "mise install",
  };
}

/** 底座：优先调官方 `mise generate devcontainer`，不可用则回退到等价模板。 */
function devcontainerBase(name: string): DevcontainerJson {
  const p = spawnSync("mise", ["generate", "devcontainer", "--name", name], { encoding: "utf8" });
  if (p.status === 0 && p.stdout && p.stdout.trim()) {
    try {
      return JSON.parse(p.stdout);
    } catch {
      /* 回退 */
    }
  }
  return fallbackDevcontainer(name);
}

export function renderDevcontainer(
  name: string,
  tc: ResolvedToolchain,
): { content: string; dockerfile?: string } {
  const dc = devcontainerBase(name);
  dc.customizations ??= {};
  dc.customizations.vscode ??= {};
  dc.customizations.vscode.extensions = [
    ...new Set([...(dc.customizations.vscode.extensions ?? []), ...tc.extensions]),
  ].sort();

  let dockerfile: string | undefined;
  if (tc.system.length) {
    const pkgs = [...new Set(tc.system.flatMap((s) => s.apt))].sort();
    dockerfile = [
      HEADER,
      "FROM mcr.microsoft.com/devcontainers/base:ubuntu",
      `RUN apt-get update && apt-get install -y --no-install-recommends ${pkgs.join(" ")} \\`,
      "    && rm -rf /var/lib/apt/lists/*",
      "",
    ].join("\n");
    delete dc.image;
    dc.build = { dockerfile: "Dockerfile" };
  }

  return { content: JSON.stringify(dc, null, 2) + "\n", dockerfile };
}

export function buildSet(tc: ResolvedToolchain, name: string): GeneratedSet {
  const files: GeneratedFile[] = [{ path: ".mise.toml", content: renderMiseToml(tc) }];
  const dc = renderDevcontainer(name, tc);
  files.push({ path: ".devcontainer/devcontainer.json", content: dc.content });
  if (dc.dockerfile) files.push({ path: "Dockerfile", content: dc.dockerfile });
  return { files };
}

export function fileStatus(f: GeneratedFile, root: string): FileStatus {
  const p = join(root, f.path);
  if (!existsSync(p)) return "create";
  return readFileSync(p, "utf8") === f.content ? "unchanged" : "change";
}

/** 手改保护：非 moule 生成的 .mise.toml 拒绝覆盖。 */
export function canOverwrite(f: GeneratedFile, root: string): { ok: boolean; reason?: string } {
  const p = join(root, f.path);
  if (!existsSync(p)) return { ok: true };
  const cur = readFileSync(p, "utf8");
  if (f.path === ".mise.toml" && !cur.startsWith("# Generated by moule")) {
    return { ok: false, reason: `已存在手写的 ${f.path}，拒绝覆盖（加 --force 强制）` };
  }
  return { ok: true };
}

export function writeGenerated(f: GeneratedFile, root: string) {
  const p = join(root, f.path);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, f.content);
}
